        <h2>Forging Process</h2>
        <p>At Ironveil Forge, each piece is developed through a structured process that prioritizes material integrity, balance, and overall 
            cohesion. While designs may vary, the underlying approach remains consistent: every step is intended to support the final form 
            of the weapon, ensuring that it functions as a complete and unified object.
        </p>

        <h3>1. Material Selection</h3>
        <p>The process begins with the selection of materials. Metals and woods are chosen based on their properties, including strength, 
            weight, durability, and response to shaping. High-carbon steel is commonly used for heads and striking components due to its 
            resilience and ability to hold form under stress, while hardwoods such as ash, oak, or hickory are selected for shafts and 
            handles because of their balance of strength and flexibility. Material selection is not treated as a purely aesthetic choice. 
            Each material contributes to how the weapon behaves as a whole. A denser wood may shift balance toward the handle, while 
            variations in metal composition can influence both weight and durability. These factors are considered early to ensure that the 
            finished piece remains consistent with its intended design.
        </p>

        <h3>2. Forming and Shaping</h3>
        <p>Once materials are selected, the primary components are shaped to establish the overall structure of the weapon. Metal elements 
            are formed to achieve the intended geometry, whether that involves creating a balanced blade, a symmetrical striking head, or a 
            reinforced structural point. At this stage, proportion is the primary focus. Dimensions are adjusted to maintain balance between 
            length, weight, and function. Even small changes can significantly affect how a piece feels and performs, so shaping is 
            approached with careful attention to scale and alignment. The goal is to create a form that is both structurally sound and 
            visually coherent.
        </p>

        <h3>3. Assembly and Balance</h3>
        <p>After individual components are shaped, they are brought together and assembled into a complete piece. This stage focuses on how 
            the elements interact, such as how the head connects to the shaft, how the grip supports handling, and how the pommel contributes to 
            overall balance. Balance is evaluated throughout assembly. Weight distribution is adjusted to ensure that the weapon feels 
            stable and controlled relative to its design. A forward-weighted piece may emphasize impact, while a more evenly balanced design 
            supports precision and maneuverability. These adjustments are made with the full structure in mind, ensuring that no single 
            component disrupts the cohesion of the whole.
        </p>

        <h3>4. Finishing and Detailing</h3>
        <p>Once the structure is complete, the weapon undergoes finishing. Metal surfaces are refined to achieve a consistent texture, 
            typically ranging from matte to lightly polished finishes. This step enhances durability while maintaining a realistic and 
            grounded appearance. Additional details, such as engravings or inscriptions, may be applied at this stage. These elements are 
            used sparingly and with intention, complementing the design rather than overwhelming it. The goal is to reinforce the identity 
            of the piece without detracting from its structure. Grips are also finalized during this phase, with materials such as leather 
            being applied to improve handling and provide a secure, consistent feel.
        </p>

        <h3>5. Final Evaluation</h3>
        <p>Before completion, each piece is evaluated as a whole. This includes checking proportions, confirming material integrity, and 
            ensuring that all components work together as intended. The weapon is assessed not just as a collection of parts, but as a 
            unified object. This final step ensures consistency across the entire collection. Each piece must meet the same standards of 
            balance, structure, and clarity that define Ironveil Forge. Only once these criteria are met is the weapon considered complete.
        </p>

        <h3>A Consistent Approach</h3>
        <p>While individual designs may differ in form and purpose, the process behind them remains consistent. By maintaining a structured 
            approach to material selection, shaping, assembly, and finishing, Ironveil Forge ensures that every piece reflects the same level 
            of care and intention. This consistency allows each weapon to feel like part of a cohesive collection, where differences in 
            design do not compromise the underlying principles that define the forge’s work.
        </p>
        
